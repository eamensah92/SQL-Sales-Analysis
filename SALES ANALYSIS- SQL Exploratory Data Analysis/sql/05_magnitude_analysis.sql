/*
===============================================================
Script:    05_magnitude_analysis.sql
Purpose:   Compare measures across dimensions (country, gender,
           category, customer).
Tables:    fact_sales, dim_customers, dim_products
Functions: COUNT, SUM, AVG, GROUP BY, LEFT JOIN
===============================================================
*/

--To find the total customers by country
SELECT country,
      COUNT(customer_key) AS Total_Customers
FROM dim_customers
GROUP BY country
ORDER BY Total_Customers DESC

--To find total customers by gender
SELECT gender,
      COUNT(customer_key) AS Total_Customers
FROM dim_customers
GROUP BY gender
ORDER BY Total_Customers DESC

--To find total products by category
SELECT category,
       COUNT(product_key)AS Total_Products
FROM dim_products
GROUP BY category
ORDER BY Total_Products DESC

--To find the average costs in each category
SELECT category,
       AVG(cost)AS Average_Cost
FROM dim_products
GROUP BY category
ORDER BY Average_Cost DESC

--To find the total revenue generated by each category
SELECT p.category,
       SUM(f.sales_amount) Total_revenue
FROM fact_sales f
LEFT JOIN dim_products p
ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY Total_revenue DESC

--To find the total revenue generated by each customers
SELECT c.customer_key,
       c.first_name,
       c.last_name,
       SUM(f.sales_amount) AS Total_revenue
FROM fact_sales f
LEFT JOIN dim_customers c
ON c.customer_key = f.customer_key
GROUP BY c.customer_key,
       c.first_name,
       c.last_name
ORDER BY Total_revenue DESC

-- To find the distribution of sold items across countries
SELECT c.country,
       SUM(f.quantity) AS Total_Sold_Items
FROM fact_sales f
LEFT JOIN dim_customers c
ON c.customer_key = f.customer_key
GROUP BY c.country
ORDER BY Total_Sold_Items DESC
